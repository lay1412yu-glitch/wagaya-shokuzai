// names.js — 食材名の表記ゆれ正規化（Task BF-C, WS4）
//
// 目的: 漢字／かな／カタカナ／送り仮名などの「同じ食材の別表記」を、
// 図鑑カタログの正規名（canonical）1つに解決する。例: ネギ→長ねぎ、
// 玉葱→玉ねぎ、たまご→卵。これにより、別表記で登録・検索しても
// キャラ画像・知識記事・カテゴリ・アイコンが正規品として引ける。
//
// 設計（循環 import の回避）:
// - このモジュールは「純粋なデータ＋純粋関数」で、一切 import しない
//   （依存グラフの葉）。そのため chars.js（import なし）
//   knowledge.js（import なし）util.js（import なし）icons.js
//   （chars.js を import）の全てから安全に import できる。
//   icons.js → chars.js → names.js、icons.js → names.js の経路でも
//   names.js は誰も import しないので循環は生じない。
// - カタログ名の集合は import せず、resolveCanonicalName の第2引数
//   （knownNames）で呼び出し側が任意に渡す。渡さない場合でも、
//   「NAME_VARIANTS のキーはカタログ名ではない／値は全てカタログ名」
//   という不変条件（テストで検証）により、正規名はそのまま返り、
//   別表記はキー照合だけで正しく解決できる。
//
// ハードルール（加工品・別食材を絶対に混ぜない）:
// - 正規名そのもの（完全一致）は常に最優先で、それ自体を返す。
//   例: 豆腐 vs 高野豆腐・木綿豆腐・絹ごし豆腐・焼き豆腐、
//   牛乳 vs 低脂肪乳、わさび vs チューブわさび、
//   卵 vs 温泉卵・味付け卵・うずら卵 はすべて別々のカタログ品であり、
//   NAME_VARIANTS のキーには絶対にならない。
// - 「刻みねぎ」は独立したカタログ品（2026-11-14 追加）。ねぎ／長ねぎ
//   とは別物であり、刻みネギ・刻み葱は刻みねぎ自身の表記ゆれとして
//   のみ解決する（長ねぎへは絶対に解決しない）。
// - 曖昧な読み「かき／カキ」（柿 とも 牡蠣 とも読める）も意図的に含めない。
// - 「コリアンダー」は葉のパクチーではなく種のスパイスとして
//   独自のカタログ品なので、パクチーへは解決しない。
// - 「唐辛子」は一味唐辛子・七味唐辛子・鷹の爪など複数の品に分かれる
//   総称なので、どれか1品へは解決しない。
// - 「米粉」は小麦粉とは別のカタログ品なので、小麦粉へは解決しない。
//
// 根拠: 各対応はカタログ実在品（js/icons.js の CATALOG＋RARITY）に対して、
// 一般的な漢字表記・かな表記・カタカナ表記・長音／送り仮名のゆれ、
// および既存の名前解決データ（chars.js の CHAR_KEYWORDS／CHAR_ALIASES、
// icons.js の NAME_ALIASES、knowledge.js の KNOWLEDGE_ALIASES）が
// 既に同一食材として扱っている別名だけを収録した。

