/** 名前 → ミュゼ版のキャラキー（キーワード先勝ち解決のみ・汎用判定なし） */
export function museCharKeyFor(name) {
  const n = String(name || "");
  if (!n) return null;
  for (const [words, key] of CHAR_KEYWORDS) {
    if (words.some((w) => n.includes(w))) return key;
  }
  return null;
}

/**
 * 食材名 → ミュゼ版キャラ画像のURL。無い場合は null（表示側で仮表示にする）。
 */
export function charUrlFor(name) {
  const raw = String(name || "");
  if (!raw) return null;
  // 表記ゆれ（ネギ・玉葱・たまご等）は正規名に解決してから引く（names.js）。
  // 正規名・未知の名前はそのまま返るので、従来の解決順は変わらない。
  const n = resolveCanonicalName(raw);
  if (CHAR_BY_NAME[n]) return CHAR_DIR + CHAR_BY_NAME[n];
  if (CHAR_ALIASES[n]) return CHAR_DIR + CHAR_ALIASES[n];
  const key = museCharKeyFor(n);
  if (key && !GENERIC_CHAR_KEYS.has(key)) {
    const file = key + ".webp";
    if (!CLAIMED_FILES.has(file)) return CHAR_DIR + file;
  }
  return null;
}

/**
 * 図鑑カタログ全食材のキャラ画像URLの一覧（重複なし）。
 * 「カタログ全体からランダムに選ぶ」用途（読み込み画面のキャラ抽選など）。
 * CHAR_BY_NAME は静的データなので、ストア初期化前でもそのまま使える。
 */
export function allCharUrls() {
  return [...new Set(Object.values(CHAR_BY_NAME))].map((f) => CHAR_DIR + f);
}

